export const LanguageProvider = ({ children }) => {
  const [currentLanguage, setCurrentLanguage] = useState(() => {
    const saved = localStorage.getItem('axansh_language');
    return saved || 'hi';
  });

  useEffect(() => {
    localStorage.setItem('axansh_language', currentLanguage);
  }, [currentLanguage]);

  const t = (key, params = {}) => {
    let text = translations[key]?.[currentLanguage] || translations[key]?.['hi'] || '';
    Object.keys(params).forEach(p => {
      text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
    });
    return text;
  };

  return (
    <LanguageContext.Provider value={{
      currentLanguage,
      setLanguage: setCurrentLanguage,
      t,
      languagesList
    }}>
      {children}
    </LanguageContext.Provider>
  );
};
